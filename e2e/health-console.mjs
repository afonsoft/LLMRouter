import { chromium } from 'playwright';
const b = await chromium.launch();
const pg = await (await b.newContext()).newPage();
pg.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') console.log('[console]', m.text().slice(0, 500)); });
pg.on('pageerror', e => console.log('[pageerror]', String(e).slice(0, 800)));
await pg.goto('http://localhost:20128/login');
await pg.fill('input[type=password]', 'test1234');
await pg.click('button[type=submit], .btn');
await pg.waitForTimeout(1500);
await pg.goto('http://localhost:20128/dashboard/health');
await pg.waitForTimeout(3000);
await b.close();

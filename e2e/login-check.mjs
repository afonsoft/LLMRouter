import { chromium } from 'playwright';
const b = await chromium.launch();
const pg = await (await b.newContext()).newPage();
pg.on('console', m => console.log('[c]', m.text().slice(0, 300)));
pg.on('pageerror', e => console.log('[e]', String(e).slice(0, 400)));
const r = await pg.goto('http://localhost:20128/login', { waitUntil: 'domcontentloaded' });
console.log('status', r.status());
await pg.waitForTimeout(8000);
console.log('inputs:', await pg.locator('input').count(), 'body len:', (await pg.textContent('body')).length);
await pg.screenshot({ path: '/tmp/login-now.png' });
await b.close();
